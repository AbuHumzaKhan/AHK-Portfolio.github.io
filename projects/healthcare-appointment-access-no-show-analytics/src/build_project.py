def create_dashboard() -> None:
    data=json.loads((ROOT / "outputs" / "dashboard_aggregates.json").read_text(encoding="utf-8"))
    data_json=json.dumps(data,separators=(",",":"))
    clinics=sorted({x["c"] for x in data["segments"]})
    specialties=sorted({x["s"] for x in data["segments"]})
    clinic_options="<option value='ALL'>All clinics</option>"+"".join(f"<option>{x}</option>" for x in clinics)
    specialty_options="<option value='ALL'>All specialties</option>"+"".join(f"<option>{x}</option>" for x in specialties)
    template=(ROOT / "reports" / "dashboard_template.html").read_text(encoding="utf-8")
    html=template.replace("CLINIC_OPTIONS",clinic_options).replace("SPECIALTY_OPTIONS",specialty_options).replace("DATA_JSON",data_json)
    (ROOT / "reports" / "dashboard.html").write_text(html,encoding="utf-8")
    (ROOT / "reports" / "dashboard_preview.html").write_text(html,encoding="utf-8")


def create_qa() -> None:
    conn=sqlite3.connect(DB); checks=[]
    def add(name,sql,expected):
        value=conn.execute(sql).fetchone()[0]
        checks.append({"check":name,"observed":value,"expected":expected,"passed":value==expected})
    add("row count matches CSV","SELECT COUNT(*) FROM appointments",7200)
    add("unique appointment IDs","SELECT COUNT(DISTINCT appointment_id) FROM appointments",7200)
    add("no negative lead days","SELECT COUNT(*) FROM appointments WHERE lead_days < 0",0)
    add("booking date not after appointment","SELECT COUNT(*) FROM appointments WHERE date(booking_date) > date(appointment_date)",0)
    add("attended rows have wait times","SELECT COUNT(*) FROM appointments WHERE status='Attended' AND wait_time_min IS NULL",0)
    add("non-attended rows have null wait","SELECT COUNT(*) FROM appointments WHERE status<>'Attended' AND wait_time_min IS NOT NULL",0)
    add("foreign-key violations","SELECT COUNT(*) FROM appointments a LEFT JOIN clinics c USING(clinic_id) WHERE c.clinic_id IS NULL",0)
    add("valid status domain","SELECT COUNT(*) FROM appointments WHERE status NOT IN ('Attended','No-show','Cancelled','Rescheduled')",0)
    add("valid reminder domain","SELECT COUNT(*) FROM appointments WHERE reminder_sent NOT IN ('Yes','No')",0)
    add("records reconcile to status totals","SELECT ABS(COUNT(*) - (SUM(status='Attended')+SUM(status='No-show')+SUM(status='Cancelled')+SUM(status='Rescheduled'))) FROM appointments",0)
    conn.close()
    pd.DataFrame(checks).to_csv(ROOT / "outputs" / "qa_checks.csv",index=False)
    if not all(c["passed"] for c in checks): raise RuntimeError(f"QA failed: {checks}")


def main() -> None:
    df=pd.read_csv(DATA)
    create_database(df)
    create_excel(df)
    create_dashboard()
    create_qa()
    print("Built SQLite database, SQL seed, Excel workbook, dashboard and QA report.")

if __name__ == "__main__": main()
