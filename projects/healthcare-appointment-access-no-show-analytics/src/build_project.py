DB = ROOT / "data" / "appointments.sqlite"


def create_database(df: pd.DataFrame) -> None:
    if DB.exists():
        DB.unlink()
    conn = sqlite3.connect(DB)
    conn.executescript((ROOT / "sql" / "schema.sql").read_text(encoding="utf-8"))
    clinics = df[["clinic_id", "clinic_name"]].drop_duplicates().sort_values("clinic_id")
    clinics.to_sql("clinics", conn, if_exists="append", index=False)
    db_df = df.copy()
    db_df["appointment_date"] = pd.to_datetime(db_df["appointment_date"]).dt.strftime("%Y-%m-%d")
    db_df["booking_date"] = pd.to_datetime(db_df["booking_date"]).dt.strftime("%Y-%m-%d")
    db_df.to_sql("appointments", conn, if_exists="append", index=False)
    conn.commit()
    conn.close()
    # The full 120-row sample seed is regenerated from the reproducible CSV.
    cols = list(df.columns)
    sample = df.head(120)
    lines = ["-- Small reproducible SQL seed sample (120 rows). Full dataset is generated by src/generate_data.py.",
             "-- Execute sql/schema.sql first. SQLite syntax."]
    for row in sample.itertuples(index=False, name=None):
        vals = []
        for v in row:
            if pd.isna(v):
                vals.append("NULL")
            elif isinstance(v, (int, float)):
                vals.append(str(int(v)) if float(v).is_integer() else str(float(v)))
            else:
                vals.append("'" + str(v).replace("'", "''") + "'")
        lines.append(f"INSERT INTO appointments ({', '.join(cols)}) VALUES ({', '.join(vals)});")
    clinic_lines = ["-- Clinic dimension seed rows."]
    for row in clinics.itertuples(index=False, name=None):
        clinic_lines.append(f"INSERT INTO clinics (clinic_id, clinic_name) VALUES ('{row[0]}', '{row[1].replace(chr(39), chr(39)*2)}');")
    (ROOT / "sql" / "seed_data.sql").write_text("\n".join(clinic_lines + [""] + lines) + "\n", encoding="utf-8")


